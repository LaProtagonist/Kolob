/** Translate engine labels/messages at the rendering boundary, without mutating them. */
export function modelText(value: string): string {
  if (value === "Производственный штат") return "Фонд оплаты труда производства";
  if (value === "Менеджер / технолог") return "Расходы работодателя: менеджер / технолог";
  let text = value;
  for (const p of [...sourceParameters].sort((a, b) => b.label.length - a.label.length)) {
    if (labels[p.id]) text = text.replaceAll(p.label, labels[p.id]);
  }
  for (const [from, to] of phrases) text = text.replaceAll(from, to);
  return text.replace(/\bM(\d+)/g, "М$1");
}

export const parameters = sourceParameters.map((p) => ({
  ...p,
  label: labels[p.id] ?? p.label,
  note: modelText(p.note),
  source: modelText(p.source),
  unit: p.unit === "FTE" ? "ставок" : p.unit.replace("FTE", "ставку"),
}));

/** Canonical default and saved names remain intact; custom names are user-owned. */
export function scenarioName(name: string): string {
  return name.replace(/^Compact Production \+ Franchise v0\.1(?=$| — копия)/,
    "Компактное производство и франшиза · версия 0.1");
}
